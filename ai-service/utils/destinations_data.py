def get_all_destinations() -> List[Dict[str, Any]]:
    """Returns all 75 destinations (50 Indian + 25 International)."""
    return DESTINATIONS_CATALOGUE


def search_destinations(query: str = "", region: str = "", category: str = "", country: str = "") -> List[Dict[str, Any]]:
    """
    Filters catalogue by keyword search, region, category, or country.
    """
    results = DESTINATIONS_CATALOGUE
    
    if country:
        country_clean = country.strip().lower()
        results = [d for d in results if d["country"].lower() == country_clean or (country_clean == "india" and d["country"].lower() == "india") or (country_clean != "india" and d["country"].lower() != "india")]
        
    if region:
        reg_clean = region.strip().lower()
        results = [d for d in results if reg_clean in d["region"].lower()]
        
    if category:
        cat_clean = category.strip().lower()
        results = [d for d in results if cat_clean in d["category"].lower()]
        
    if query:
        q = query.strip().lower()
        matched = []
        for d in results:
            if (
                q in d["name"].lower() or 
                q in d["state"].lower() or 
                q in d["country"].lower() or 
                q in d["region"].lower() or 
                q in d["category"].lower() or 
                q in d["description"].lower() or
                any(q in kw for kw in d.get("keywords", [])) or
                any(q in hl.lower() for hl in d.get("highlights", []))
            ):
                matched.append(d)
        results = matched
        
    return results
